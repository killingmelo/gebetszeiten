// Optional local signing: create keystore.properties (gitignored) to sign release builds.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) load(FileInputStream(keystorePropertiesFile))
}

android {
    namespace = "de.gebetszeiten"
    compileSdk = 36

    defaultConfig {
        applicationId = "de.gebetszeiten"
        minSdk = 26
        targetSdk = 36
        versionCode = 12
        versionName = "0.1.11"
    }

    flavorDimensions += "connectivity"
    productFlavors {
        // Privacy-pure default: no INTERNET, fully offline calculation.
        create("offline") {
            dimension = "connectivity"
            isDefault = true
        }
        // Optional variant that can fetch exact official Diyanet times online.
        create("online") {
            dimension = "connectivity"
            applicationIdSuffix = ".online"
            versionNameSuffix = "-online"
        }
    }

    signingConfigs {
        if (keystorePropertiesFile.exists()) {
            create("release") {
                storeFile = file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
            if (keystorePropertiesFile.exists()) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlin {
        compilerOptions {
            jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17)
        }
    }

    buildFeatures {
        compose = true
    }
}

